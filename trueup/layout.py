_DEFAULT_DOCS_DIR = Config().layout_docs_dir
"""The docs directory when no config is given: the default of `[layout]
docs_dir` (D14.4)."""

_EXEMPT_BASENAMES: frozenset[str] = frozenset({"README.md", "CHANGELOG.md", "SKILL.md"})
"""A page with this exact basename, at any depth, is never a candidate
(D10.2): a directory README, a package changelog or a skill page."""

_EXEMPT_SEGMENTS: frozenset[str] = frozenset(
    {"fixtures", "testdata", "__snapshots__", "vendor", "third_party", "node_modules"}
)
"""A path segment that takes a page out of the candidate set, the same
fixture set `hygiene._duplicate` uses (D6.12)."""

CODE_SEGMENTS: tuple[str, ...] = (
    "agents",
    "claude",
    "prompts",
    "rules",
    "skills",
    "templates",
)
"""A path segment that holds Markdown-as-code: agent definitions, skill
bodies, prompts, rules and templates that a tool reads as input. A page
under one is never a candidate (D13.1). `[layout] code_dirs` adds more."""


def code_dirs(cfg: Config | None) -> tuple[str, ...]:
    """Give the Markdown-as-code segments in force: `CODE_SEGMENTS` plus `[layout] code_dirs` (D13.1).

    Args:
        cfg: The loaded `trueup.toml`, or `None` for the defaults.

    Returns:
        The segment names.
    """
    return CODE_SEGMENTS + (cfg.layout_code_dirs if cfg is not None else ())


_TOOLING_SEGMENTS: frozenset[str] = frozenset(
    {"change_log", "changelog", "locale", "content", "_templates"}
)
"""A path segment that takes a page out of the `locate` candidate set: a
change log tree, a translation tree, a content tree or a template tree
that tooling reads in place (D15.13). `_is_candidate` does not use it."""

_CONTENT_TREE_MIN = 20
"""A directory with more candidate pages than this is a content tree and
gives one `doc-tree` row, not a row per page (D15.13)."""

_TEXT_READ_CAP = 1024 * 1024
"""The largest page, in bytes, that layout reads as text (D15.22)."""

_GENERATED_HEAD = re.compile(
    r"(?i)\b(auto-?generated|generated by|code generated|@generated|do not edit)\b"
)
"""The marker that a page in its first lines is generated (D15.13)."""

_AGENT_KEYS: frozenset[str] = frozenset({"name", "description"})
"""Front matter keys that, with no `type` key, mark an agent or skill
definition, not a page (D13.1)."""

_STANDARD_ROOT_NAMES: frozenset[str] = frozenset(
    {
        "readme.md",
        "changelog.md",
        "contributing.md",
        "license.md",
        "security.md",
        "code_of_conduct.md",
        "agents.md",
        "claude.md",
        "support.md",
        "accessibility.md",
        "pull_request_template.md",
    }
)
"""The lower-cased standard root page names (D10.2). The match is exact
and ignores case; it never matches `README.old.md` the way the guard's
`README*` glob does. The last three are GitHub community health pages
that GitHub reads at the root (docs/reference/trueup.md, the GitHub
table)."""

_GITHUB_TEMPLATE_DIR = "pull_request_template"
"""The lower-cased root directory where GitHub reads more than one pull
request template. A page in it is not a candidate."""


_REFCHECK_LINE = re.compile(
    r"^(?P<path>.+):(?P<line>\d+): \[(?P<kind>[a-z-]+)\] (?P<detail>.*)$"
)
"""One failure line of a `refcheck` finding's evidence, the same shape
`docrules._REFCHECK_FAILURE_LINE` parses."""

_BROKEN_LINK_PREFIX = "link does not resolve: "
"""The fixed text `ref_check._check_g` puts before the target of a
`broken-link` failure's detail."""

_RENAME_LINE = re.compile(r"^R\d+\t(?P<old>[^\t]+)\t(?P<new>[^\t]+)$")
"""One `--name-status` rename line: `R<score>\\t<old>\\t<new>`."""

_HASH_LINE = re.compile(r"^[0-9a-f]{4,40}$")
"""One `git log --format=%h` commit hash line."""

_KEPT_REASON = "a [[keep]] entry keeps it in place"

_UNTRACKED_REASON = "the page is not tracked; git add it, then run trueup check again"
"""The reason an untracked page gets no move (D15.27)."""

_SHALLOW_NOTE = "; history unavailable (shallow clone)"
"""The end of a `standard`-basis evidence in a shallow clone (D15.25)."""
"""The evidence reason of a page whose `doc-misplaced` id is a keep id
(D10.2, D10.6): the page gets its finding but no move."""


@dataclass(frozen=True)
class Move:
    """One proposed move of a misplaced page or directory (D10.6).

    Attributes:
        id: `"move:<source>"`; `source` ends in `/` for a directory.
        source: The current repo-relative path.
        target: The proposed repo-relative path.
        kind: `"file"` or `"dir"`.
        basis: `"history"`, `"link"` or `"standard"`.
        evidence: One line naming the source of the target, for example
            `"renamed from docs/design/ in 1a2b3c4"`.
        pages: The `doc-misplaced` pages this move covers, sorted.
    """

    id: str
    source: str
    target: str
    kind: str
    basis: str
    evidence: str
    pages: tuple[str, ...]


@dataclass(frozen=True)
class LayoutResult:
    """The result of one `locate` run (D10.6).

    Attributes:
        findings: One `doc-misplaced` finding per candidate page.
        moves: The proposed moves, sorted by id.
        evidence_notes: Refcheck finding id to the hint text D10.6 adds to
            its evidence. `report.collect` applies this with
            `dataclasses.replace`; the finding id never changes (I-39).
    """

    findings: list[Finding]
    moves: list[Move]
    evidence_notes: dict[str, str]


def locate(
    root: Path,
    survey: Survey,
    cfg: Config | None,
    findings: list[Finding],
    only: frozenset[str] | None = None,
) -> LayoutResult:
    """Find each misplaced page and propose where it belongs (D10.2, D10.6, D10.12).

    Args:
        root: The repository root.
        survey: The survey to check.
        cfg: The loaded `trueup.toml`, or `None` for the defaults.
        findings: The findings `docrules.docrules_findings` already gave,
            for the `refcheck` row's `broken-link` findings (D10.2). The
            scratch set comes from `hygiene.scratch_looking`, the helper
            the `scratch` and `artifact` rows use (D12.11).
        only: The changed set of a scoped check, or `None` for a full
            check. When it is set, only candidates in `only` give a
            finding, there are no moves and no notes, and no git command
            runs (D10.6, D10.12). The move plan comes from a full check
            only.

    Returns:
        The candidate pages as `doc-misplaced` findings, the moves a
        person can approve, and the broken-link evidence notes. A page
        whose `doc-misplaced` id a `[[keep]]` id matches (exact or by
        prefix, `findings.keep_match`, D15.8) gets its finding but
        no move and no note, and a move whose target exists in the work
        tree is refused (D10.6). A page that git does not track gets its
        finding and no move, and a directory that holds an untracked file
        is never one move (D15.27). Every
        list is empty when no page is a candidate; the git history scan
        does not run in that case.
    """
    from trueup.hygiene import scratch_looking  # lazy: hygiene imports layout

    scratch_paths = frozenset(
        path for path in survey.files if scratch_looking(path, cfg)
    )
    root_allow = cfg.root_allow if cfg is not None else ()
    docs_dir = cfg.layout_docs_dir if cfg is not None else _DEFAULT_DOCS_DIR
    candidates = sorted(
        path
        for path in survey.files
        if _is_candidate(
            path,
            scratch_paths,
            root_allow=root_allow,
            code_dirs=code_dirs(cfg),
            docs_dir=docs_dir,
        )
        and not _is_agent_definition(root / path, root)
    )
    candidates, tree_rows = _drop_tooling_pages(root, survey, candidates, docs_dir)
    if only is not None:
        scoped = [
            _page_finding(path, None, "the move plan comes from a full check", docs_dir)
            for path in candidates
            if path in only
        ]
        return LayoutResult(findings=scoped, moves=[], evidence_notes={})
    broken_links = _broken_link_targets(findings)
    if not candidates:
        # The history scan only earns its cost when a candidate exists
        # (D10.6), but a broken link can still point at a file that
        # already lives under the docs directory with no candidate in sight, so the
        # fix-the-link hint still runs.
        notes = _broken_link_evidence_notes(broken_links, [], frozenset(), survey.files)
        return LayoutResult(findings=tree_rows, moves=[], evidence_notes=notes)

    protect = cfg.protect if cfg is not None else ()
    keep = cfg.keep if cfg is not None else {}
    kept = frozenset(
        path
        for path in candidates
        if findings_mod.keep_match(f"doc-misplaced:{path}", keep) is not None
    )
    # D15.27: `git mv` moves only a tracked page, so an untracked page,
    # or a directory that holds an untracked file, gets no move.
    untracked = (
        frozenset(path for path in survey.files if path not in survey.tracked)
        if survey.tracked
        else frozenset()
    )
    survey_files = frozenset(survey.files)
    history_map = _history_renames(root)
    # The standard target reads the docs mode in force, resolved by tier
    # at read time; `trueup.toml` keeps its stored value (D12.9).
    resolved = replace(
        cfg if cfg is not None else Config(),
        docs=config_mod.resolve_docs(cfg, survey.tier),
    )
    targets = _resolve_targets(
        root,
        candidates,
        history_map,
        broken_links,
        survey_files,
        resolved,
        shallow=_is_shallow(root),
    )

    dir_moves, consumed = _directory_moves(
        root,
        targets,
        survey.files,
        protect,
        kept | untracked,
        history_map,
        broken_links,
    )
    file_moves = [
        Move(
            id=f"move:{path}",
            source=path,
            target=targets[path][0],
            kind="file",
            basis=targets[path][1],
            evidence=targets[path][2],
            pages=(path,),
        )
        for path in candidates
        if path not in consumed and path not in kept and path not in untracked
    ]

    allowed = [move for move in dir_moves + file_moves if not _vetoed(move, protect)]
    reasons: dict[str, str] = dict.fromkeys(kept, _KEPT_REASON)
    reasons.update(
        (path, _UNTRACKED_REASON) for path in candidates if path in untracked
    )
    free: list[Move] = []
    for move in allowed:
        if os.path.lexists(root / move.target.rstrip("/")):
            # `git mv` onto an existing file fails, and onto an existing
            # directory it nests the source, so the move is refused (D10.6).
            for page in move.pages:
                reasons[page] = f"target {move.target} exists, move it by hand"
            continue
        free.append(move)
    shared = _collisions(free)
    kept_moves: list[Move] = []
    move_by_page: dict[str, Move] = {}
    for move in free:
        if move.id in shared:
            for page in move.pages:
                reasons[page] = (
                    f"target {shared[move.id]} is claimed by more than one page"
                )
            continue
        kept_moves.append(move)
        for page in move.pages:
            move_by_page[page] = move
    kept_moves.sort(key=lambda move: move.id)

    page_findings = [
        _page_finding(
            path, move_by_page.get(path), reasons.get(path, "protected"), docs_dir
        )
        for path in candidates
    ]
    evidence_notes = _broken_link_evidence_notes(
        broken_links, kept_moves, frozenset(candidates), survey.files
    )
    return LayoutResult(
        findings=page_findings + tree_rows,
        moves=kept_moves,
        evidence_notes=evidence_notes,
    )


def _is_generated_page(root: Path, rel: str) -> bool:
    """Say whether a page declares itself generated in its first 5 lines (D15.13).

    Args:
        root: The repository root.
        rel: The repo-relative path of the page. `fsread.read_head` reads it.

    Returns:
        True when one of the first 5 lines matches `_GENERATED_HEAD`.
        False when `fsread.read_head` refuses the file (D15.22).
    """
    raw = fsread.read_head(root, rel, 4096)
    if raw is None:
        return False
    head = raw.decode("utf-8", errors="replace")
    return any(_GENERATED_HEAD.search(line) for line in head.splitlines()[:5])


def _drop_tooling_pages(
    root: Path, survey: Survey, candidates: list[str], docs_dir: str
) -> tuple[list[str], list[Finding]]:
    """Drop the candidates that a move would break (D15.13).

    The order is: tooling segments, generated pages, a directory that
    non-Markdown files name, then a content tree of more than
    `_CONTENT_TREE_MIN` pages.

    Args:
        root: The repository root.
        survey: The survey, for the files that can name a directory.
        candidates: The sorted candidate pages.
        docs_dir: The docs directory name, for the evidence text.

    Returns:
        The pages that stay candidates, and one `doc-tree` `info` finding
        for each content tree (empty list when there is none).
    """
    kept = [
        path
        for path in candidates
        if not _TOOLING_SEGMENTS.intersection(Path(path).parts[:-1])
        and not _is_generated_page(root, path)
    ]
    if not kept:
        return [], []
    from trueup.hygiene import _reference_index  # lazy: hygiene imports layout

    others = [path for path in survey.files if not path.endswith((".md", ".markdown"))]
    corpus = _reference_index(root, others)[1]
    kept = [path for path in kept if not _directory_is_named(path, corpus)]
    counts: dict[str, int] = {}
    for path in kept:
        parts = Path(path).parts
        if len(parts) > 1:
            counts[parts[0]] = counts.get(parts[0], 0) + 1
    trees = {name for name, count in counts.items() if count > _CONTENT_TREE_MIN}
    rows = [
        Finding(
            id=f"doc-tree:{name}/",
            rule="doc-tree",
            category="files",
            severity="info",
            path=f"{name}/",
            evidence=f"holds {counts[name]} pages; trueup does not move a content tree",
            action=f"none; the pages stay outside {docs_dir}/",
            auto=False,
        )
        for name in sorted(trees)
    ]
    return [p for p in kept if Path(p).parts[0] not in trees or "/" not in p], rows


def _directory_is_named(path: str, corpus: str) -> bool:
    """Say whether non-Markdown text names the page's directory (D15.13).

    Args:
        path: The candidate page.
        corpus: The joined text of the non-Markdown files.

    Returns:
        True when `<dir>/` occurs in `corpus` for the page's directory, or
        for its parent when the parent has two or more segments.
    """
    directory = posixpath.dirname(path)
    if not directory:
        return False
    names = [directory]
    parent = posixpath.dirname(directory)
    if len(parent.split("/")) >= 2:
        names.append(parent)
    return any(f"{name}/" in corpus for name in names)


def _page_finding(
    path: str,
    move: Move | None,
    reason: str = "protected",
    docs_dir: str = _DEFAULT_DOCS_DIR,
) -> Finding:
    """Build the one `doc-misplaced` finding of a candidate page (D10.2).

    Args:
        path: The candidate's repo-relative path.
        move: The move that covers `path`, or `None` when there is none.
        reason: Why there is no move, used only when `move` is `None`:
            `protected` when a `protect` glob vetoed every move that
            would have covered it, the shared-target text of
            `_collisions` (D10.6), the existing-target text, the
            `[[keep]]` text, or the scoped-check text.
        docs_dir: The docs directory that the evidence names (D14.4).

    Returns:
        A `files`, `warn`, `auto=False` finding. Its evidence names the
        move and target when `move` is given, or gives `reason`; its
        action approves that move, or asks for a `[[keep]]` entry.
    """
    base = f"Markdown page outside {docs_dir}/"
    if move is not None:
        evidence = f"{base}; {move.id} to {move.target} ({move.basis}: {move.evidence})"
        action = f"approve {move.id}"
    else:
        evidence = f"{base}; {reason}"
        action = "add a [[keep]] entry"
    return Finding(
        id=f"doc-misplaced:{path}",
        rule="doc-misplaced",
        category="files",
        severity="warn",
        path=path,
        evidence=evidence,
        action=action,
        auto=False,
    )


def _is_candidate(
    path: str,
    scratch_paths: frozenset[str],
    *,
    root_allow: Sequence[str] = (),
    code_dirs: Sequence[str] = CODE_SEGMENTS,
    docs_dir: str = _DEFAULT_DOCS_DIR,
) -> bool:
    """Say whether a surveyed path is a `doc-misplaced` candidate (D10.2, D13.1, D14.4).

    Args:
        path: The repo-relative POSIX path.
        scratch_paths: The paths `hygiene.scratch_looking` accepts (D12.11).
        root_allow: The `[root] allow` globs of `trueup.toml`. A root
            page that one of them names is allowed at the root. The match
            is `fnmatch.fnmatchcase` on the whole path, the match the
            `scratch` row uses for a root file.
        code_dirs: The Markdown-as-code segments: `CODE_SEGMENTS` plus
            `[layout] code_dirs`.
        docs_dir: The `[layout] docs_dir` name. A page under a segment
            with this name is not a candidate.

    Returns:
        True when the path ends in `.md` or `.markdown`, no path segment
        is `docs_dir` or starts with `.`, no segment is a fixture segment
        (`_EXEMPT_SEGMENTS`) or a directory segment in `code_dirs`, the
        basename is not `README.md`,
        `CHANGELOG.md` or `SKILL.md`, the path is not a standard root
        page at depth 0 (`_STANDARD_ROOT_NAMES`, case-insensitive), the
        path is not a page in the root `PULL_REQUEST_TEMPLATE/` directory, no
        `root_allow` glob names it at depth 0, and `scratch_paths` does
        not hold the path.
    """
    if not path.endswith((".md", ".markdown")):
        return False
    parts = Path(path).parts
    if docs_dir in parts:
        return False
    if any(part.startswith(".") for part in parts):
        return False
    if any(part in _EXEMPT_SEGMENTS for part in parts):
        return False
    if any(part in code_dirs for part in parts[:-1]):
        return False
    if parts[-1] in _EXEMPT_BASENAMES:
        return False
    if len(parts) == 1 and parts[0].lower() in _STANDARD_ROOT_NAMES:
        return False
    if len(parts) == 2 and parts[0].lower() == _GITHUB_TEMPLATE_DIR:
        return False
    if len(parts) == 1 and any(
        fnmatch.fnmatchcase(path, pattern) for pattern in root_allow
    ):
        return False
    return path not in scratch_paths


def _inside_repository(target: str) -> bool:
    """Say whether a target path stays inside the repository (D10.6).

    Args:
        target: A history, link or directory-link target.

    Returns:
        True when the normalized POSIX path is relative (no leading `/`)
        and has no `..` segment. The standard target is always inside, by
        construction.
    """
    clean = posixpath.normpath(target)
    return not clean.startswith("/") and ".." not in clean.split("/")


def _acceptable(
    target: str, survey_files: frozenset[str], docs_dir: str = _DEFAULT_DOCS_DIR
) -> bool:
    """Say whether a history or a link target passes the D10.6 acceptance checks.

    Args:
        target: The candidate old path (history) or the resolved missing
            path (link).
        survey_files: Every path the survey holds, for "does not exist now".
        docs_dir: The `[layout] docs_dir` name (D14.4).

    Returns:
        True when `target` stays inside the repository (D10.6), is not
        a path the survey already holds, and has a `docs_dir` segment or
        is a standard root page. Two moves with one target are found later, by
        `_collisions` (D10.6).
    """
    if not _inside_repository(target):
        return False
    if target in survey_files:
        return False
    parts = Path(target).parts
    if docs_dir in parts:
        return True
    return len(parts) == 1 and parts[0].lower() in _STANDARD_ROOT_NAMES


def _resolve_targets(
    root: Path,
    candidates: list[str],
    history_map: dict[str, tuple[str, str]],
    broken_links: list[tuple[Finding, str, bool]],
    survey_files: frozenset[str],
    cfg: Config | None,
    shallow: bool = False,
) -> dict[str, tuple[str, str, str]]:
    """Give each candidate its target, basis and evidence (D10.6, D15.25).

    History is tried first, then a broken link naming the candidate's own
    basename, then a broken link naming the basename of a directory that
    holds the candidate, then the standard. Two candidates can get the
    same target here; `_collisions` finds them after all moves are built
    (D10.6).

    Args:
        root: The repository root.
        candidates: The candidate paths, in the order they are resolved.
        history_map: `path` to `(old path, evidence hash or note)`, from
            `_history_renames`. `_history_target` follows it back along
            the rename chain (D15.25).
        broken_links: Each `broken-link` finding with its resolved target,
            from `_broken_link_targets`.
        survey_files: Every path the survey holds.
        cfg: The loaded config, or `None` for the defaults.
        shallow: The repository is a shallow clone. A `standard`-basis
            evidence then ends with `_SHALLOW_NOTE` (D15.25).

    Returns:
        Each candidate's `(target, basis, evidence)`.
    """
    docs_dir = cfg.layout_docs_dir if cfg is not None else _DEFAULT_DOCS_DIR
    names = _basename_index(survey_files)
    targets: dict[str, tuple[str, str, str]] = {}
    remaining: list[str] = []

    def accept(old_path: str) -> bool:
        return _acceptable(old_path, survey_files, docs_dir)

    for path in candidates:
        old = _history_target(path, history_map, accept)
        if old is not None:
            target, commit = old
            targets[path] = (target, "history", f"renamed from {target} in {commit}")
        else:
            remaining.append(path)

    still: list[str] = []
    for path in remaining:
        found = _link_target(path, names, broken_links, survey_files, docs_dir)
        if found is not None:
            target, finding = found
            targets[path] = (
                target,
                "link",
                f"named by a broken link in {finding.path}",
            )
        else:
            still.append(path)
    remaining = still

    dir_links = _directory_link_targets(
        remaining, names, broken_links, survey_files, docs_dir
    )
    for path, (target, finding) in dir_links.items():
        targets[path] = (target, "link", f"named by a broken link in {finding.path}")
    remaining = [path for path in remaining if path not in dir_links]

    for path in remaining:
        text = _read_text(root, path)
        target, basis, evidence = _standard_target(path, text, cfg)
        targets[path] = (
            target,
            basis,
            evidence + _SHALLOW_NOTE if shallow else evidence,
        )
    return targets


def _history_target(
    path: str,
    history_map: dict[str, tuple[str, str]],
    accept: Callable[[str], bool],
) -> tuple[str, str] | None:
    """Follow the rename chain of one path back to the first old path that passes (D15.25).

    Args:
        path: The candidate's repo-relative path.
        history_map: New path to `(old path, evidence)`, from
            `_history_renames`.
        accept: The test an old path must pass, `_acceptable` for a page.

    Returns:
        The newest `(old path, evidence)` on the chain that `accept`
        passes, or `None` when the chain ends or comes back to a path it
        saw (a cycle) first.
    """
    seen = {path}
    current = history_map.get(path)
    while current is not None:
        if accept(current[0]):
            return current
        if current[0] in seen:
            return None
        seen.add(current[0])
        current = history_map.get(current[0])
    return None


def _basename_index(survey_files: frozenset[str]) -> dict[str, list[str]]:
    """Index every surveyed file and every directory of surveyed files by basename (D10.6).

    Args:
        survey_files: Every path the survey holds.

    Returns:
        Basename to the sorted file and directory paths with that
        basename. The link step uses it to say "exactly one surveyed
        file, or one directory of surveyed files" over the whole survey,
        not only over the candidates.
    """
    found: dict[str, set[str]] = {}
    for path in survey_files:
        parts = path.split("/")
        for depth in range(1, len(parts) + 1):
            found.setdefault(parts[depth - 1], set()).add("/".join(parts[:depth]))
    return {name: sorted(paths) for name, paths in found.items()}


def _link_target(
    path: str,
    names: dict[str, list[str]],
    broken_links: list[tuple[Finding, str, bool]],
    survey_files: frozenset[str],
    docs_dir: str = _DEFAULT_DOCS_DIR,
) -> tuple[str, Finding] | None:
    """Give one candidate's link target, when a broken link names it uniquely (D10.6).

    Args:
        path: The candidate to resolve.
        names: Every surveyed file and directory by basename, from
            `_basename_index`.
        broken_links: Each `broken-link` finding with its resolved target.
        survey_files: Every path the survey holds.
        docs_dir: The `[layout] docs_dir` name, for `_acceptable`.

    Returns:
        The target and the finding that named it, when exactly one
        surveyed file or directory shares the target's basename, that
        path is `path`, and the target passes `_acceptable`. `None`
        otherwise. A link that named a directory is left for
        `_directory_link_targets`, the step-2 directory case.
    """
    for finding, target, is_dir in broken_links:
        if is_dir:
            continue
        name = Path(target.rstrip("/")).name
        if names.get(name, []) == [path] and _acceptable(
            target, survey_files, docs_dir
        ):
            return target, finding
    return None


def _acceptable_directory(
    target: str, survey_files: frozenset[str], docs_dir: str = _DEFAULT_DOCS_DIR
) -> bool:
    """Say whether a directory-level link target passes the D10.6 acceptance checks.

    Args:
        target: The resolved directory's old path, no trailing slash.
        survey_files: Every path the survey holds, to say whether a file
            sits under `target` now.
        docs_dir: The `[layout] docs_dir` name (D14.4).

    Returns:
        True when `target` stays inside the repository, has a `docs_dir`
        segment, and no surveyed file sits under it now (D10.6: "O has a
        docs segment", "O does not exist now").
    """
    if not _inside_repository(target) or docs_dir not in Path(target).parts:
        return False
    prefix = f"{target}/"
    return not any(path.startswith(prefix) for path in survey_files)


def _directory_link_targets(
    remaining: list[str],
    names: dict[str, list[str]],
    broken_links: list[tuple[Finding, str, bool]],
    survey_files: frozenset[str],
    docs_dir: str = _DEFAULT_DOCS_DIR,
) -> dict[str, tuple[str, Finding]]:
    """Give the link target of every unresolved page under a matched directory (D10.6, step 2, directory case).

    A broken link can also name a missing directory, not only a missing
    file. When exactly one surveyed path shares that directory's
    basename, that path is a directory, and it holds at least one
    unresolved candidate, every
    candidate under it gets the matching target: the link's directory
    plus the candidate's own path relative to its directory.

    Args:
        remaining: The candidates still unresolved (history and the
            file-level link step already ran).
        names: Every surveyed file and directory by basename, from
            `_basename_index`.
        broken_links: Each `broken-link` finding with its resolved
            target and whether it named a directory.
        survey_files: Every path the survey holds.
        docs_dir: The `[layout] docs_dir` name, for `_acceptable_directory`.

    Returns:
        Candidate path to `(target, finding)`, for every candidate
        covered by a uniquely matched, acceptable directory link.
    """
    by_dir: dict[str, list[str]] = {}
    for path in survey_files:
        parts = Path(path).parts
        for depth in range(1, len(parts)):
            directory = "/".join(parts[:depth])
            by_dir.setdefault(directory, []).append(path)

    remaining_set = frozenset(remaining)
    resolved: dict[str, tuple[str, Finding]] = {}
    for finding, target, is_dir in broken_links:
        if not is_dir:
            continue
        matches = names.get(Path(target).name, [])
        if len(matches) != 1 or matches[0] not in by_dir:
            continue
        directory = matches[0]
        covered = sorted(page for page in by_dir[directory] if page in remaining_set)
        if not covered:
            continue
        if not _acceptable_directory(target, survey_files, docs_dir):
            continue
        for page in covered:
            rel = posixpath.relpath(page, directory)
            page_target = posixpath.normpath(posixpath.join(target, rel))
            resolved[page] = (page_target, finding)
    return resolved


def _standard_target(
    path: str, text: str | None, cfg: Config | None
) -> tuple[str, str, str]:
    """Give a candidate's standard target (D10.6, step 3, D14.4).

    Args:
        path: The candidate's repo-relative path.
        text: The candidate's own text, to read a `type` front matter
            field, or `None` when it could not be read.
        cfg: The loaded config, or `None` for the defaults.

    Returns:
        `(<docs_dir>/<type>/<basename>, "standard", evidence)` when
        `[layout] types` is on (D15.29), `docs` is not `"readme"`, and
        the page has a valid `type`; otherwise
        `(<docs_dir>/<basename>, "standard", evidence)`.
    """
    basename = Path(path).name
    effective = cfg if cfg is not None else Config()
    docs_dir = effective.layout_docs_dir
    # D15.29: the `[layout]` switch decides; `refs.layout` already set it.
    types_on = effective.layout_types
    page_type = (
        _front_matter_type(text)
        if types_on and effective.docs != "readme" and text
        else None
    )
    if page_type is not None:
        return (
            f"{docs_dir}/{page_type}/{basename}",
            "standard",
            f"the standard target for a {page_type} page",
        )
    return (
        f"{docs_dir}/{basename}",
        "standard",
        "the standard target for an untyped page",
    )


def _is_agent_definition(path: Path, root: Path | None = None) -> bool:
    """Say whether a Markdown file is an agent or skill definition (D13.1).

    Args:
        path: The file on disk.
        root: The repository root. `fsread.read_head` refuses a symlink
            that leaves it (D15.22). When `None`, the parent directory of
            `path` is the root.

    Returns:
        True when the file starts with a front matter block whose
        top-level keys hold `name` and `description` and no `type`. The
        block is read by `ref_check._front_matter` with `skip_other`, so a
        line that is not a top-level `<key>:` line or a list item (a
        folded value) is skipped (D15.30). False when the file cannot be
        read or has no closed block in its first 4 KiB.
    """
    base = path.parent if root is None else root
    raw = fsread.read_head(base, path.relative_to(base).as_posix(), 4096)
    if raw is None:
        return False
    head = raw.decode("utf-8", errors="replace")
    fields = _front_matter(head, skip_other=True)
    if fields is None:
        return False
    return _AGENT_KEYS <= fields.keys() and "type" not in fields


def _front_matter_type(text: str) -> str | None:
    """Read the `type` front matter field of one page's text (D10.6).

    Args:
        text: The page's content.

    Returns:
        The value of the first `type` line, when it is one of
        `_PAGE_TYPES`; `None` when there is no valid front matter block
        (the checker's `ref_check._front_matter`, D15.30), no `type`
        field, or the value is not a known type.
    """
    fields = _front_matter(text)
    if fields is None or "type" not in fields:
        return None
    value = fields["type"][1]
    return value if value in _PAGE_TYPES else None


def _directory_moves(
    root: Path,
    targets: dict[str, tuple[str, str, str]],
    files: tuple[str, ...],
    protect: tuple[str, ...],
    kept: frozenset[str],
    history_map: dict[str, tuple[str, str]],
    broken_links: list[tuple[Finding, str, bool]],
) -> tuple[list[Move], frozenset[str]]:
    """Group candidates under one directory into a single `dir` move (D10.6, units).

    Args:
        root: The repository root, to find a target directory that exists
            on disk (D12.11).
        targets: Each candidate's `(target, basis, evidence)`, from
            `_resolve_targets`.
        files: Every surveyed path, to find each candidate's siblings.
        protect: The `protect` globs of `trueup.toml`.
        kept: The candidates whose `doc-misplaced` id is a keep id.
        history_map: `path` to `(old path, evidence)`, from
            `_history_renames`, to place a non-Markdown file.
        broken_links: Each `broken-link` finding with its resolved
            target, to place a non-Markdown file.

    Returns:
        The directory moves, and the candidate paths they cover. The
        largest directory that holds only matching candidates and
        non-Markdown files is picked first (shallowest directories are
        tried first), so a qualifying ancestor wins over a qualifying
        child, unless its computed target already holds a file this move
        does not account for, or that another move fills, in which case a
        narrower, unoccupied directory is tried next. A non-Markdown file
        goes with a directory move only when evidence places it at its
        new path (`_placed`): the standard places pages, not the code or
        assets beside them. A directory that holds a
        `protect`-matched file, of any kind, is never bundled into one
        move (I-38): its candidates fall through to individual file
        moves, which `_vetoed` can still stop on their own. A directory
        that holds a kept page is never one move either (D10.2, D10.6):
        the kept page stays, and its siblings fall through to file moves.
    """
    by_dir: dict[str, list[str]] = {}
    for path in files:
        parts = Path(path).parts
        for depth in range(1, len(parts)):
            directory = "/".join(parts[:depth])
            by_dir.setdefault(directory, []).append(path)

    assigned: set[str] = set()
    moves: list[Move] = []
    for directory in sorted(by_dir, key=lambda name: name.count("/")):
        files_under = by_dir[directory]
        relevant = [
            path for path in files_under if path in targets and path not in assigned
        ]
        if not relevant:
            continue
        non_markdown = any(
            not path.endswith((".md", ".markdown")) for path in files_under
        )
        if len(relevant) < 2 and not non_markdown:
            # A directory move earns its keep only when it replaces at
            # least two page moves, or carries along a non-Markdown file
            # that would otherwise stay behind; a lone candidate with no
            # sibling at all stays the simpler file move (D10.6, units).
            continue
        if any(matches_ignore(path, protect) or path in kept for path in files_under):
            continue
        base: list[str] | None = None
        pages: list[str] = []
        others: list[str] = []
        ok = True
        for path in files_under:
            if path in assigned:
                ok = False
                break
            if not path.endswith((".md", ".markdown")):
                others.append(path)
                continue
            info = targets.get(path)
            if info is None:
                ok = False
                break
            target_parts = info[0].split("/")
            rel_parts = posixpath.relpath(path, directory).split("/")
            if (
                len(target_parts) <= len(rel_parts)
                or target_parts[-len(rel_parts) :] != rel_parts
            ):
                ok = False
                break
            this_base = target_parts[: -len(rel_parts)]
            if base is None:
                base = this_base
            elif this_base != base:
                ok = False
                break
            pages.append(path)
        if not ok or base is None or not pages:
            continue
        target_dir = "/".join(base)
        if any(
            not _placed(
                posixpath.join(target_dir, posixpath.relpath(path, directory)),
                path,
                history_map,
                broken_links,
            )
            for path in others
        ):
            # No evidence places this code or asset file under the target,
            # so the directory does not move as one unit (D10.6, units).
            continue
        if os.path.lexists(root / target_dir):
            # The target directory exists on disk, empty or holding only
            # an ignored file. `git mv` would nest the source in it, so
            # the pages fall back to file moves (D12.11).
            continue
        inside = f"{directory}/"
        if any(path.startswith(f"{target_dir}/") for path in files) or any(
            info[0].startswith(f"{target_dir}/")
            for page, info in targets.items()
            if not page.startswith(inside)
        ):
            # The computed target already holds a file this move does
            # not account for, or another move puts a page there.
            # `git mv` into an existing directory nests the source, so
            # this ancestor is not "such an S" (D10.6, units). A
            # narrower, unoccupied directory is tried next.
            continue
        pages.sort()
        basis, evidence = targets[pages[0]][1], targets[pages[0]][2]
        moves.append(
            Move(
                id=f"move:{directory}/",
                source=f"{directory}/",
                target="/".join(base) + "/",
                kind="dir",
                basis=basis,
                evidence=evidence,
                pages=tuple(pages),
            )
        )
        assigned.update(files_under)
    return moves, frozenset(assigned)


def _placed(
    expected: str,
    path: str,
    history_map: dict[str, tuple[str, str]],
    broken_links: list[tuple[Finding, str, bool]],
) -> bool:
    """Say whether evidence places a non-Markdown file at a new path (D10.6, units).

    Args:
        expected: The path the file gets when its directory moves.
        path: The file's current repo-relative path.
        history_map: `path` to `(old path, evidence)`, from
            `_history_renames`.
        broken_links: Each `broken-link` finding with its resolved target.

    Returns:
        True when history renamed `path` from `expected`, or when a broken
        link names `expected` or a directory that holds `expected`.
    """
    old = history_map.get(path)
    if old is not None and old[0] == expected:
        return True
    return any(
        expected == target or expected.startswith(f"{target}/")
        for _finding, target, _is_dir in broken_links
    )


def _collisions(moves: list[Move]) -> dict[str, str]:
    """Find the moves that share a target with another move (D10.6).

    A file target that falls inside a directory move's target is in the
    group of that directory target. `git mv` cannot put two sources on one
    target, so no move in a group of more than one is proposed.

    Args:
        moves: The moves that `protect` did not veto.

    Returns:
        Move id to its group target, for each move in a group of more than
        one move. Empty when every target is unique.
    """
    dir_targets = sorted({move.target for move in moves if move.kind == "dir"}, key=len)
    groups: dict[str, list[str]] = {}
    for move in moves:
        key = move.target
        if move.kind == "file":
            key = next(
                (target for target in dir_targets if move.target.startswith(target)),
                move.target,
            )
        groups.setdefault(key, []).append(move.id)
    return {
        move_id: key
        for key, members in groups.items()
        if len(members) > 1
        for move_id in members
    }


def _vetoed(move: Move, protect: tuple[str, ...]) -> bool:
    """Say whether `protect` stops one move (D10.6, vetoes; I-38).

    Args:
        move: The proposed move.
        protect: The `protect` globs of `trueup.toml`.

    Returns:
        True when the source, the target, or a parent directory of
        either matches a `protect` glob.
    """
    for endpoint in (move.source, move.target):
        clean = endpoint.rstrip("/")
        parts = Path(clean).parts
        for depth in range(1, len(parts) + 1):
            prefix = "/".join(parts[:depth])
            if matches_ignore(prefix, protect) or matches_ignore(f"{prefix}/", protect):
                return True
    return False


def _broken_link_targets(findings: list[Finding]) -> list[tuple[Finding, str, bool]]:
    """Give each `broken-link` refcheck finding with its resolved target (D10.6, link).

    Args:
        findings: The merged findings `locate` received.

    Returns:
        One `(finding, target, is_dir)` triple per `refcheck` finding
        whose evidence parses as a `broken-link` failure, `target`
        resolved against the linking file's own directory, with no
        fragment. `is_dir` is True when the link as written named a
        directory (it ended in `/`), so `target` is a directory path
        with no trailing slash.
    """
    results: list[tuple[Finding, str, bool]] = []
    for finding in findings:
        if finding.rule != "refcheck":
            continue
        match = _REFCHECK_LINE.match(finding.evidence)
        if match is None or match.group("kind") != "broken-link":
            continue
        detail = match.group("detail")
        if not detail.startswith(_BROKEN_LINK_PREFIX):
            continue
        written = detail[len(_BROKEN_LINK_PREFIX) :]
        path_part = written.split("#", 1)[0]
        if not path_part:
            continue
        is_dir = path_part.endswith("/")
        target = posixpath.normpath(
            posixpath.join(posixpath.dirname(finding.path), path_part)
        )
        results.append((finding, target, is_dir))
    return results


def _broken_link_evidence_notes(
    broken_links: list[tuple[Finding, str, bool]],
    moves: list[Move],
    candidates: frozenset[str],
    files: tuple[str, ...],
) -> dict[str, str]:
    """Build the D10.6 broken-link evidence notes, after the move plan is final (I-39).

    Args:
        broken_links: Each `broken-link` finding with its resolved
            target and whether it named a directory.
        moves: The moves `protect` did not veto.
        candidates: Every `doc-misplaced` candidate path.
        files: Every surveyed path.

    Returns:
        Refcheck finding id to hint text: `"the target is now at <source>;
        approve <move id>"` when the resolved target is a move's target,
        or `"a file with this name is at <path>; fix the link"` when the
        target matches exactly one surveyed file by basename and that
        file is not a candidate. Neither hint changes the finding id.
    """
    move_by_target = {move.target.rstrip("/"): move for move in moves}
    file_set = frozenset(files)
    names = _basename_index(file_set)
    notes: dict[str, str] = {}
    for finding, target, _is_dir in broken_links:
        clean = target.rstrip("/")
        move = move_by_target.get(clean)
        if move is not None:
            notes[finding.id] = f"the target is now at {move.source}; approve {move.id}"
            continue
        name = Path(clean).name
        matches = [path for path in names.get(name, []) if path in file_set]
        if len(matches) == 1 and matches[0] not in candidates:
            notes[finding.id] = (
                f"a file with this name is at {matches[0]}; fix the link"
            )
    return notes


def _history_renames(root: Path) -> dict[str, tuple[str, str]]:
    """Find the newest rename into each path, committed or staged (D10.6, history).

    Args:
        root: The repository root.

    Returns:
        New path to `(old path, a short hash, or "a staged change")`. A
        staged rename wins over a committed one for the same new path;
        among committed renames, the newest commit wins. Git gives paths
        from the top of the work tree, so when `root` is a subdirectory
        only the renames with both paths below it stay, with its prefix
        taken off (D15.25). Empty when `git` cannot be run.
    """
    renames: dict[str, tuple[str, str]] = {}
    prefix = _show_prefix(root)
    if prefix is None:
        return renames

    def add(new: str, old: str, note: str) -> None:
        if new.startswith(prefix) and old.startswith(prefix):
            renames.setdefault(new[len(prefix) :], (old[len(prefix) :], note))

    # `core.quotePath=false` gives a non-ASCII path as written, not as a
    # quoted octal string that matches no surveyed path (D10.7).
    staged = subprocess.run(
        [
            "git",
            "-c",
            "core.quotePath=false",
            "diff",
            "--cached",
            "-M",
            "--diff-filter=R",
            "--name-status",
        ],
        cwd=root,
        capture_output=True,
        text=True,
        errors="surrogateescape",  # arch: D12.10
        check=False,
    )
    if staged.returncode == 0:
        for line in staged.stdout.splitlines():
            match = _RENAME_LINE.match(line)
            if match is not None:
                add(match.group("new"), match.group("old"), "a staged change")

    log = subprocess.run(
        [
            "git",
            "-c",
            "core.quotePath=false",
            "log",
            "-M",
            "--diff-filter=R",
            "--name-status",
            "--format=%h",
        ],
        cwd=root,
        capture_output=True,
        text=True,
        errors="surrogateescape",  # arch: D12.10
        check=False,
    )
    if log.returncode != 0:
        return renames
    commit = ""
    for line in log.stdout.splitlines():
        if not line:
            continue
        match = _RENAME_LINE.match(line)
        if match is not None:
            add(match.group("new"), match.group("old"), commit)
            continue
        if _HASH_LINE.match(line):
            commit = line
    return renames


def _show_prefix(root: Path) -> str | None:
    """Give the path of `root` below the top of its work tree (D15.25).

    Args:
        root: The repository root, or a directory inside a work tree.

    Returns:
        The output of `git rev-parse --show-prefix`: `""` at the top, or
        the relative path with a trailing `/`. `None` when git fails.
    """
    result = subprocess.run(
        ["git", "-c", "core.quotePath=false", "rev-parse", "--show-prefix"],
        cwd=root,
        capture_output=True,
        text=True,
        errors="surrogateescape",  # arch: D12.10
        check=False,
    )
    if result.returncode != 0:
        return None
    return result.stdout.rstrip("\n")


def _is_shallow(root: Path) -> bool:
    """Say whether the repository is a shallow clone (D15.25).

    Args:
        root: The repository root.

    Returns:
        True when `git rev-parse --is-shallow-repository` prints `true`.
    """
    result = subprocess.run(
        ["git", "rev-parse", "--is-shallow-repository"],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    return result.returncode == 0 and result.stdout.strip() == "true"


def _read_text(root: Path, rel: str) -> str | None:
    """Read a tracked file as text through `fsread`, 1 MiB at most (D15.22).

    Args:
        root: The repository root.
        rel: The repo-relative path.

    Returns:
        The decoded text, or `None` when the file cannot be read, is a
        device, a symlink out of the root, or is longer than 1 MiB.
    """
    return fsread.read_text_capped(root, rel, _TEXT_READ_CAP)
