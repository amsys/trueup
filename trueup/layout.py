"""The `doc-misplaced` row and the move locator (D10.2, D10.6, D10.12).

`locate` finds each Markdown page that sits outside `docs/` and is not a
standard root page, and proposes where it belongs. It tries three sources
of evidence, in order: the git rename history of the page, a broken link
that names the page's old path, and the repository's own standard
(`docs/<type>/<basename>`). A directory whose pages all move the same way
becomes one move for the whole directory. A `protect` glob vetoes a move
and turns its evidence into "protected". A `[[keep]]` entry on a page's
`doc-misplaced` id keeps the page in place, and a target that exists is
refused.

`locate` only builds the plan; it changes no file. `trueup.apply` carries
out an approved `move:` id (D10.7), and `trueup.report.collect` is the
caller that merges `LayoutResult.findings` into the plan and applies
`LayoutResult.evidence_notes` onto the refcheck findings (D10.6).
"""

